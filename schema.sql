create table public.students (
  student_id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  student_no text not null,
  first_name text not null,
  last_name text not null,
  year_level smallint not null,
  email text not null,
  course_id smallint null,
  constraint students_pkey primary key (student_id),
  constraint students_email_key unique (email),
  constraint students_email_unique unique (email),
  constraint students_student_no_key unique (student_no),
  constraint students_student_no_unique unique (student_no),
  constraint students_course_id_fkey foreign KEY (course_id) references courses (course_id)
) TABLESPACE pg_default;

create table public.courses (
  course_id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  course_code text not null,
  course_name text not null,
  department_name text not null,
  department_id bigint null,
  constraint courses_pkey primary key (course_id),
  constraint courses_course_code_key unique (course_code),
  constraint courses_course_code_unique unique (course_code),
  constraint courses_department_id_fkey foreign KEY (department_id) references departments (department_id)
) TABLESPACE pg_default;

create table public.departments (
  department_id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  department_name text null,
  constraint departments_pkey primary key (department_id)
) TABLESPACE pg_default;